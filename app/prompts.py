"""Промпты и правила генерации: grounded-ответ с цитатами + явный отказ."""

SYSTEM_RULES = (
    "Ты — ассистент, который отвечает СТРОГО на основе предоставленных фрагментов "
    "(контекста). Правила:\n"
    "1. Используй только факты из фрагментов. Ничего не выдумывай.\n"
    "2. После каждого утверждения ставь ссылку на источник в формате [номер], "
    "где номер — это номер фрагмента из контекста. Можно несколько: [1][3].\n"
    "3. Если во фрагментах нет ответа на вопрос — честно скажи, что в базе нет "
    "релевантной информации, и не пытайся ответить из общих знаний.\n"
    "4. Отвечай на русском языке, кратко и по делу."
)

# Подсказка, дописываемая к контексту, чтобы закрепить grounded-поведение.
ANSWER_INSTRUCTION = (
    "Ответь на вопрос пользователя, опираясь только на фрагменты выше. "
    "Каждое утверждение подкрепляй ссылкой [номер]. Если ответа в фрагментах нет — "
    "напиши, что информации в базе недостаточно."
)

REFUSAL_NO_CONTEXT = (
    "В базе не найдено релевантных фрагментов по этому вопросу. "
    "Ответить по имеющимся данным невозможно."
)

REFUSAL_EMPTY_QUESTION = "Задайте вопрос."


def build_context_block(sources: list[dict]) -> str:
    """Нумерованный контекст для LLM: [1] name :: text."""
    lines = []
    for i, src in enumerate(sources, 1):
        name = src.get("name", "")
        header = f"[{i}] {name}".strip()
        lines.append(f"{header}\n{src['text']}")
    return "\n\n".join(lines)


def build_user_prompt(question: str, sources: list[dict]) -> str:
    context = build_context_block(sources)
    return (
        f"Фрагменты из базы знаний:\n\n{context}\n\n"
        f"---\nВопрос: {question}\n\n{ANSWER_INSTRUCTION}"
    )
